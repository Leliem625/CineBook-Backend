-- unaccent() không phải IMMUTABLE nên không dùng trực tiếp trong index được.
-- Hàm bọc này dùng cho tìm kiếm tiếng Việt không dấu.
CREATE OR REPLACE FUNCTION f_unaccent(text) RETURNS text
    LANGUAGE sql IMMUTABLE PARALLEL SAFE STRICT
AS $$ SELECT public.unaccent('public.unaccent', $1) $$;

-- ---------------------------------------------------------------------
-- Tỉnh/thành
-- ---------------------------------------------------------------------
CREATE TABLE province (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100) NOT NULL,
    slug        VARCHAR(100) NOT NULL UNIQUE,
    sort_order  INTEGER      NOT NULL DEFAULT 100
);

-- ---------------------------------------------------------------------
-- Thể loại (id theo TMDB để đồng bộ)
-- ---------------------------------------------------------------------
CREATE TABLE genre (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tmdb_id  INTEGER      UNIQUE,
    name     VARCHAR(100) NOT NULL,
    slug     VARCHAR(100) NOT NULL UNIQUE
);

-- ---------------------------------------------------------------------
-- Phim
-- ---------------------------------------------------------------------
CREATE TABLE movie (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tmdb_id           INTEGER       UNIQUE,                 -- null nếu admin tạo tay
    slug              VARCHAR(255)  NOT NULL UNIQUE,
    title_vi          VARCHAR(255)  NOT NULL,
    original_title    VARCHAR(255),
    overview          TEXT,
    runtime_min       INTEGER       CHECK (runtime_min > 0),
    release_date_vn   DATE,
    age_rating        VARCHAR(5)    CHECK (age_rating IN ('P', 'K', 'T13', 'T16', 'T18')),
    status            VARCHAR(20)   NOT NULL DEFAULT 'COMING_SOON'
                                    CHECK (status IN ('COMING_SOON', 'NOW_SHOWING', 'ENDED')),
    country           VARCHAR(100),
    original_language VARCHAR(10),
    poster_url        VARCHAR(500),
    backdrop_url      VARCHAR(500),
    trailer_key       VARCHAR(50),                          -- YouTube video key
    directors         TEXT,                                 -- tên, phân tách bằng dấu phẩy
    casts             TEXT,
    tmdb_score        NUMERIC(3, 1) CHECK (tmdb_score BETWEEN 0 AND 10),
    tmdb_popularity   NUMERIC(12, 3),
    manually_edited   BOOLEAN       NOT NULL DEFAULT FALSE, -- true: job TMDB không ghi đè
    synced_at         TIMESTAMPTZ,
    created_at        TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ   NOT NULL DEFAULT now()
);

CREATE INDEX idx_movie_status_release ON movie (status, release_date_vn DESC);
-- Tìm kiếm không dấu, gần đúng: WHERE f_unaccent(lower(title_vi)) % f_unaccent(lower(:q))
CREATE INDEX idx_movie_title_trgm ON movie USING gin (f_unaccent(lower(title_vi)) gin_trgm_ops);
CREATE INDEX idx_movie_original_title_trgm ON movie USING gin (f_unaccent(lower(original_title)) gin_trgm_ops);

CREATE TABLE movie_genre (
    movie_id  BIGINT NOT NULL REFERENCES movie (id) ON DELETE CASCADE,
    genre_id  BIGINT NOT NULL REFERENCES genre (id),
    PRIMARY KEY (movie_id, genre_id)
);
CREATE INDEX idx_movie_genre_genre ON movie_genre (genre_id);

