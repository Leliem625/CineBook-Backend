-- ---------------------------------------------------------------------
-- Đơn đặt vé. Tạo ở trạng thái HELD khi khách bấm "Tiếp tục" ở bước chọn ghế.
-- Tiền là số nguyên VND (BR-13), không dùng số thực.
-- ---------------------------------------------------------------------
CREATE TABLE booking (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code              VARCHAR(8)    NOT NULL UNIQUE,   -- mã đặt vé 8 ký tự, bỏ ký tự dễ nhầm (0/O, 1/I)
    guest_session_id  VARCHAR(64)   NOT NULL,          -- id phiên khách (cookie ký số, FR-301)
    user_id           BIGINT,                          -- tài khoản khách (M10); chưa có bảng nên chưa có FK
    customer_name     VARCHAR(100),                    -- 3 trường liên hệ điền ở bước sau (FR-307)
    email             VARCHAR(255),
    phone             VARCHAR(20),                     -- chuẩn hóa +84
    showtime_id       BIGINT        NOT NULL REFERENCES showtime (id),
    status            VARCHAR(20)   NOT NULL DEFAULT 'HELD'
                      CHECK (status IN ('HELD', 'PAYMENT_PENDING', 'CONFIRMED', 'CHECKED_IN', 'PAYMENT_FAILED',
                                        'EXPIRED', 'CANCELLED', 'REFUND_PENDING', 'REFUNDED', 'REFUND_FAILED')),
    hold_expires_at   TIMESTAMPTZ,                     -- hết hạn giữ ghế (BR-05); null khi không còn ở trạng thái giữ
    subtotal          BIGINT        NOT NULL DEFAULT 0 CHECK (subtotal >= 0),
    discount          BIGINT        NOT NULL DEFAULT 0 CHECK (discount >= 0),
    total             BIGINT        NOT NULL DEFAULT 0,
    voucher_id        BIGINT,                          -- chưa có bảng voucher nên chưa có FK
    idempotency_key   VARCHAR(100),                    -- BR-10
    version           INTEGER       NOT NULL DEFAULT 0,
    created_at        TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ   NOT NULL DEFAULT now(),

    CHECK (total = subtotal - discount AND total >= 0),                  -- tổng tiền không âm (BR-14)
    CHECK (status <> 'HELD' OR hold_expires_at IS NOT NULL),             -- đang giữ ghế thì phải có hạn
    UNIQUE (id, showtime_id)                                             -- để booking_seat ràng buộc cùng suất chiếu
);

-- BR-04: một phiên khách chỉ có tối đa 1 booking HELD cho mỗi suất chiếu
CREATE UNIQUE INDEX uq_booking_one_hold ON booking (showtime_id, guest_session_id) WHERE status = 'HELD';

-- BR-10: gửi lại cùng Idempotency-Key thì trả kết quả cũ (key chỉ cần duy nhất trong phạm vi một phiên khách)
CREATE UNIQUE INDEX uq_booking_idempotency ON booking (guest_session_id, idempotency_key)
    WHERE idempotency_key IS NOT NULL;

-- Job hết hạn giữ ghế quét các booking HELD đã quá hạn (BR-05)
CREATE INDEX idx_booking_hold_expiry ON booking (hold_expires_at) WHERE status = 'HELD';
CREATE INDEX idx_booking_guest_session ON booking (guest_session_id);
CREATE INDEX idx_booking_showtime ON booking (showtime_id);

-- ---------------------------------------------------------------------
-- Ghế trong booking, giá đã chốt tại thời điểm giữ (BR-12).
-- showtime_id lặp lại ở đây để DB đảm bảo ghế thuộc đúng suất chiếu của booking.
-- ---------------------------------------------------------------------
CREATE TABLE booking_seat (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id   BIGINT       NOT NULL,
    showtime_id  BIGINT       NOT NULL,
    seat_id      BIGINT       NOT NULL,
    seat_type    VARCHAR(10)  NOT NULL CHECK (seat_type IN ('STANDARD', 'VIP', 'COUPLE')),
    price        BIGINT       NOT NULL CHECK (price >= 0),

    UNIQUE (booking_id, seat_id),
    FOREIGN KEY (booking_id, showtime_id) REFERENCES booking (id, showtime_id) ON DELETE CASCADE,
    FOREIGN KEY (showtime_id, seat_id) REFERENCES showtime_seat (showtime_id, seat_id)
);

CREATE INDEX idx_booking_seat_seat ON booking_seat (showtime_id, seat_id);

-- ---------------------------------------------------------------------
-- Lịch sử chuyển trạng thái của booking (máy trạng thái SRS 6.2), chỉ thêm, không sửa.
-- ---------------------------------------------------------------------
CREATE TABLE booking_status_history (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id   BIGINT       NOT NULL REFERENCES booking (id) ON DELETE CASCADE,
    from_status  VARCHAR(20),                         -- null khi mới tạo
    to_status    VARCHAR(20)  NOT NULL,
    reason       VARCHAR(200),
    actor        VARCHAR(50),                         -- guest / system / admin...
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE INDEX idx_booking_status_history_booking ON booking_status_history (booking_id, created_at);

-- ---------------------------------------------------------------------
-- Nối showtime_seat.booking_id (đã có từ V4) tới booking. Từ đây mỗi ghế HELD/SOLD
-- của một suất trỏ tới đúng một booking tồn tại (BR-01).
-- ---------------------------------------------------------------------
ALTER TABLE showtime_seat
    ADD CONSTRAINT fk_showtime_seat_booking FOREIGN KEY (booking_id) REFERENCES booking (id);
