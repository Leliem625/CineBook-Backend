-- =====================================================================
-- V3: Hệ thống rạp, cụm rạp, phòng chiếu, ghế (module cinema - SRS M02)
-- =====================================================================

CREATE TABLE cinema_chain (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(100) NOT NULL UNIQUE,
    slug         VARCHAR(100) NOT NULL UNIQUE,
    logo_url     VARCHAR(500),
    description  TEXT,
    active       BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE cinema (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chain_id     BIGINT        NOT NULL REFERENCES cinema_chain (id),
    province_id  BIGINT        NOT NULL REFERENCES province (id),
    name         VARCHAR(150)  NOT NULL,
    slug         VARCHAR(150)  NOT NULL UNIQUE,
    address      VARCHAR(300)  NOT NULL,
    latitude     NUMERIC(9, 6),
    longitude    NUMERIC(9, 6),
    phone        VARCHAR(20),
    active       BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at   TIMESTAMPTZ   NOT NULL DEFAULT now()
);
CREATE INDEX idx_cinema_province ON cinema (province_id);
CREATE INDEX idx_cinema_chain ON cinema (chain_id);

-- ---------------------------------------------------------------------
-- Phòng chiếu
-- ---------------------------------------------------------------------
CREATE TABLE room (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cinema_id    BIGINT       NOT NULL REFERENCES cinema (id),
    name         VARCHAR(50)  NOT NULL,
    grid_rows    INTEGER      NOT NULL CHECK (grid_rows BETWEEN 1 AND 50),   -- kích thước lưới sơ đồ (gồm lối đi)
    grid_cols    INTEGER      NOT NULL CHECK (grid_cols BETWEEN 1 AND 60),
    active       BOOLEAN      NOT NULL DEFAULT TRUE,
    UNIQUE (cinema_id, name),
    UNIQUE (id, cinema_id)            -- cho phép showtime tham chiếu (room_id, cinema_id)
);

-- Định dạng phòng hỗ trợ; showtime tham chiếu bảng này để đảm bảo BR-51
CREATE TABLE room_format (
    room_id  BIGINT      NOT NULL REFERENCES room (id) ON DELETE CASCADE,
    format   VARCHAR(10) NOT NULL CHECK (format IN ('F2D', 'F3D', 'IMAX', 'F4DX')),
    PRIMARY KEY (room_id, format)
);

-- ---------------------------------------------------------------------
-- Ghế vật lý. grid_x/grid_y là vị trí trên lưới để vẽ sơ đồ (ô không có ghế = lối đi)
-- ---------------------------------------------------------------------
CREATE TABLE seat (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id       BIGINT      NOT NULL REFERENCES room (id) ON DELETE CASCADE,
    row_label     VARCHAR(3)  NOT NULL,                 -- A, B, C...
    seat_number   INTEGER     NOT NULL CHECK (seat_number > 0),
    grid_x        INTEGER     NOT NULL CHECK (grid_x >= 0),
    grid_y        INTEGER     NOT NULL CHECK (grid_y >= 0),
    seat_type     VARCHAR(10) NOT NULL DEFAULT 'STANDARD'
                              CHECK (seat_type IN ('STANDARD', 'VIP', 'COUPLE')),
    pair_seat_id  BIGINT      REFERENCES seat (id),     -- ghế đôi: trỏ tới ghế cặp (BR-06)
    sellable      BOOLEAN     NOT NULL DEFAULT TRUE,    -- false: ghế hỏng / dành riêng
    UNIQUE (room_id, row_label, seat_number),
    UNIQUE (room_id, grid_y, grid_x),
    CHECK ((seat_type = 'COUPLE') = (pair_seat_id IS NOT NULL))
);
