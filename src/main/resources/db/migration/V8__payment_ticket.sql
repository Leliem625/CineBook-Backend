-- ---------------------------------------------------------------------
-- Mỗi lần khách bấm "Thanh toán" tạo một dòng payment (một booking có thể thử thanh toán nhiều lần).
-- Tiền là số nguyên VND (BR-13).
-- ---------------------------------------------------------------------
CREATE TABLE payment (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id       BIGINT       NOT NULL REFERENCES booking (id),
    provider         VARCHAR(10)  NOT NULL CHECK (provider IN ('VNPAY', 'MOMO', 'STRIPE')),
    txn_ref          VARCHAR(64)  NOT NULL UNIQUE,     -- mã tham chiếu CineBook tự sinh, gửi cho cổng (vnp_TxnRef)
    provider_txn_id  VARCHAR(100) UNIQUE,              -- mã giao dịch do cổng trả về (vnp_TransactionNo); null tới khi có callback
    amount           BIGINT       NOT NULL CHECK (amount > 0),
    status           VARCHAR(20)  NOT NULL DEFAULT 'CREATED'
                     CHECK (status IN ('CREATED', 'PENDING', 'SUCCEEDED', 'FAILED', 'CANCELLED_BY_USER',
                                       'AMOUNT_MISMATCH', 'REFUND_REQUESTED', 'REFUNDED', 'REFUND_FAILED')),
    response_code    VARCHAR(10),                      -- mã kết quả cổng trả về (vnp_ResponseCode), để tra cứu khi lỗi
    idempotency_key  VARCHAR(100),                     -- BR-10
    version          INTEGER      NOT NULL DEFAULT 0,
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    paid_at          TIMESTAMPTZ
);

-- Một booking chỉ có tối đa 1 lần thanh toán thành công: chặn xác nhận hai lần ngay tại DB
CREATE UNIQUE INDEX uq_payment_one_success ON payment (booking_id) WHERE status = 'SUCCEEDED';

-- BR-10: tạo thanh toán gửi lại cùng Idempotency-Key thì trả kết quả cũ
CREATE UNIQUE INDEX uq_payment_idempotency ON payment (booking_id, idempotency_key)
    WHERE idempotency_key IS NOT NULL;

CREATE INDEX idx_payment_booking ON payment (booking_id);
-- Job đối soát: payment PENDING quá 15 phút (FR-505, phòng khi mất IPN)
CREATE INDEX idx_payment_pending ON payment (created_at) WHERE status = 'PENDING';

-- ---------------------------------------------------------------------
-- Mọi callback nhận từ cổng (IPN và return URL), lưu nguyên văn để đối soát (FR-503).
-- payment_id có thể null: callback sai chữ ký hoặc mã tham chiếu không tồn tại vẫn phải được ghi lại (BR-21).
-- ---------------------------------------------------------------------
CREATE TABLE payment_callback (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id       BIGINT       REFERENCES payment (id),
    provider         VARCHAR(10)  NOT NULL CHECK (provider IN ('VNPAY', 'MOMO', 'STRIPE')),
    callback_type    VARCHAR(10)  NOT NULL CHECK (callback_type IN ('IPN', 'RETURN')),
    txn_ref          VARCHAR(64),                      -- mã tham chiếu lấy từ callback, để tra khi chưa gắn được payment
    payload          JSONB        NOT NULL,            -- tham số callback nguyên văn
    signature_valid  BOOLEAN      NOT NULL,
    received_at      TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE INDEX idx_payment_callback_payment ON payment_callback (payment_id);
CREATE INDEX idx_payment_callback_txn_ref ON payment_callback (txn_ref);

-- ---------------------------------------------------------------------
-- Vé điện tử: mỗi ghế của một booking đã thanh toán là một vé (FR-311, FR-404).
-- ---------------------------------------------------------------------
CREATE TABLE ticket (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id    BIGINT       NOT NULL,
    showtime_id   BIGINT       NOT NULL,
    seat_id       BIGINT       NOT NULL REFERENCES seat (id),
    qr_token      VARCHAR(64)  NOT NULL UNIQUE,        -- token ký số, không đoán được (FR-404)
    status        VARCHAR(10)  NOT NULL DEFAULT 'VALID' CHECK (status IN ('VALID', 'CANCELLED')),
    checked_in_at TIMESTAMPTZ,
    checked_in_by BIGINT,                              -- nhân viên soát vé; chưa có bảng staff_account nên chưa có FK
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),

    UNIQUE (booking_id, seat_id),
    -- vé phải cùng suất chiếu với booking
    FOREIGN KEY (booking_id, showtime_id) REFERENCES booking (id, showtime_id),
    FOREIGN KEY (showtime_id, seat_id) REFERENCES showtime_seat (showtime_id, seat_id)
);

-- Mỗi ghế của mỗi suất chỉ có tối đa 1 vé còn hiệu lực
CREATE UNIQUE INDEX uq_ticket_active_seat ON ticket (showtime_id, seat_id) WHERE status = 'VALID';
CREATE INDEX idx_ticket_booking ON ticket (booking_id);
