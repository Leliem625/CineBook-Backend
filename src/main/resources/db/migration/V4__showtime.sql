-- =====================================================================
-- V4: Suất chiếu và trạng thái ghế theo suất (module showtime - SRS M02, M03)
-- =====================================================================

CREATE TABLE showtime (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    movie_id        BIGINT       NOT NULL REFERENCES movie (id),
    room_id         BIGINT       NOT NULL,
    cinema_id       BIGINT       NOT NULL,   -- phi chuẩn hóa để lọc lịch chiếu theo rạp/khu vực nhanh
    start_at        TIMESTAMPTZ  NOT NULL,
    end_at          TIMESTAMPTZ  NOT NULL,   -- hết phim
    occupied_until  TIMESTAMPTZ  NOT NULL,   -- hết phim + quảng cáo + dọn phòng (BR-50)
    format          VARCHAR(10)  NOT NULL,
    language        VARCHAR(10)  NOT NULL CHECK (language IN ('SUBTITLED', 'DUBBED', 'ORIGINAL')),
    status          VARCHAR(20)  NOT NULL DEFAULT 'SCHEDULED'
                                 CHECK (status IN ('SCHEDULED', 'ON_SALE', 'CLOSED', 'FINISHED', 'CANCELLED')),
    high_demand     BOOLEAN      NOT NULL DEFAULT FALSE,  -- bật phòng chờ ảo (BR-55)
    version         INTEGER      NOT NULL DEFAULT 0,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),

    -- cinema_id phải đúng là rạp của phòng
    FOREIGN KEY (room_id, cinema_id) REFERENCES room (id, cinema_id),
    -- BR-51: định dạng phải được phòng hỗ trợ
    FOREIGN KEY (room_id, format) REFERENCES room_format (room_id, format),
    CHECK (end_at > start_at),
    CHECK (occupied_until >= end_at),
    -- BR-50: hai suất cùng phòng không chồng giờ (trừ suất đã hủy)
    CONSTRAINT ex_showtime_no_overlap
        EXCLUDE USING gist (room_id WITH =, tstzrange(start_at, occupied_until) WITH &&)
        WHERE (status <> 'CANCELLED')
);

CREATE INDEX idx_showtime_cinema_start ON showtime (cinema_id, start_at);
CREATE INDEX idx_showtime_movie_start ON showtime (movie_id, start_at);
CREATE INDEX idx_showtime_start ON showtime (start_at) WHERE status IN ('SCHEDULED', 'ON_SALE');

-- ---------------------------------------------------------------------
-- Trạng thái từng ghế cho từng suất. Đây là bảng nóng nhất của hệ thống:
-- giữ ghế = UPDATE ... WHERE status = 'AVAILABLE' (BR-01, BR-03).
-- Khóa chính ghép (showtime_id, seat_id) => mỗi ghế mỗi suất đúng 1 dòng.
-- ---------------------------------------------------------------------
CREATE TABLE showtime_seat (
    showtime_id  BIGINT       NOT NULL REFERENCES showtime (id) ON DELETE CASCADE,
    seat_id      BIGINT       NOT NULL REFERENCES seat (id),
    status       VARCHAR(10)  NOT NULL DEFAULT 'AVAILABLE'
                              CHECK (status IN ('AVAILABLE', 'HELD', 'SOLD', 'BLOCKED')),
    booking_id   BIGINT,      -- FK tới booking được thêm ở migration của module booking
    version      INTEGER      NOT NULL DEFAULT 0,
    updated_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    PRIMARY KEY (showtime_id, seat_id),
    -- ghế HELD/SOLD phải thuộc một booking; AVAILABLE/BLOCKED thì không
    CHECK ((status IN ('HELD', 'SOLD')) = (booking_id IS NOT NULL))
);

CREATE INDEX idx_showtime_seat_booking ON showtime_seat (booking_id) WHERE booking_id IS NOT NULL;
